// Generate 7 days x 24 hours heatmap engagement data with realistic peak activity
export const generateHeatmapData = (): HeatmapCell[] => {
  const cells: HeatmapCell[] = [];
  for (let day = 0; day < 7; day++) {
    for (let hour = 0; hour < 24; hour++) {
      let base = 15;
      if (day >= 1 && day <= 5) {
        if (hour >= 8 && hour <= 10) base = 85;
        else if (hour >= 12 && hour <= 14) base = 75;
        else if (hour >= 17 && hour <= 19) base = 92;
        else if (hour >= 10 && hour <= 17) base = 60;
      } else {
        if (hour >= 10 && hour <= 15) base = 65;
        else if (hour >= 18 && hour <= 21) base = 70;
        else base = 20;
      }
      const noise = (Math.sin(day * 3 + hour * 7) * 8 + 8) % 15;
      cells.push({
        day,
        hour,
        intensity: Math.min(100, Math.max(5, Math.round(base + noise))),
      });
    }
  }
  return cells;
};

